import { findingsSummary, imageSource } from '../../services/evaluation';
import './ReportTemplate.css';

// สีประจำแต่ละคลาสรอยโรค (ตรงกับ Backend)
const LESION_COLORS = {
  OpticDisc:    '#0000FF',
  Macula:       '#00FF00',
  Exudates:     '#00FF00',
  Hemorrhages:  '#0000FF',
  Drusen:       '#FF00FF',
};

const ReportTemplate = ({ patientId, eyeLaterality, lesions, severity, imageBase64, maskBase64, simulated, approximate }) => {

  const now = new Date();
  const dateStr = now.toLocaleDateString('en-GB');
  const timeStr = now.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });

  return (
    <div id="pdf-report-content" className="report-container">

      {/* ========== 1. HEADER ========== */}
      <div className="report-header">
        <div className="header-left">
          <h1 className="brand-title">
            <span className="brand-jaksu">Jaksu</span>
            <span className="brand-health">Health</span>
          </h1>
          <p className="brand-subtitle">Retinal Fundus Analysis Report (Research Prototype)</p>
        </div>
        <div className="header-right">
          <p>Date : {dateStr}</p>
          <p>Time: {timeStr}</p>
        </div>
      </div>

      {/* ========== 2. CLINICAL INFORMATION ========== */}
      <div className="section-container">
        <h3 className="section-title">CLINICAL INFORMATION</h3>
        <div className="info-grid">
          <div className="info-box">
            <span className="info-label">PATIENT ID</span>
            <p className="info-value">{patientId || 'N/A'}</p>
          </div>
          <div className="info-box">
            <span className="info-label">EYE LATERALITY</span>
            <p className="info-value">{eyeLaterality || 'N/A'}</p>
          </div>
        </div>
      </div>

      {/* ========== 3. BIOMARKER VISUALISATION ========== */}
      <div className="section-container">
        <h3 className="section-title">BIOMARKER VISUALISATION</h3>
        <div className="image-wrapper">
          {imageBase64 && (
            <img src={imageBase64} alt="Fundus Original" className="base-image" />
          )}
          {maskBase64 && (
            <img
              src={imageSource(maskBase64)}
              alt="AI Mask Overlay"
              className="overlay-image"
            />
          )}
        </div>
      </div>

      {/* ========== 4. ANALYSIS METRICS ========== */}
      <div className="section-container">
        <h3 className="section-title">ANALYSIS METRICS</h3>

        <div className="metrics-summary">
          <div className="metric-item">
            <span className="metric-label">Preliminary Assessment</span>
            <span className="metric-value-text">{severity}</span>
          </div>
        </div>
        <p style={{ fontSize: '11px', marginBottom: '10px' }}>{findingsSummary(lesions || [])}</p>
        {simulated && (
          <div style={{ background: '#fff3cd', border: '1px solid #ffeeba', padding: '6px 10px', borderRadius: '4px', marginBottom: '8px' }}>
            <strong style={{ color: '#856404', fontSize: '11px' }}>SIMULATION MODE:</strong>
            <span style={{ color: '#856404', fontSize: '11px' }}> These results are generated by offline simulation and DO NOT represent real AI model output.</span>
          </div>
        )}

        {/* Lesion Detail Table */}
        <table className="analysis-table">
          <thead>
            <tr>
              <th>LESION TYPE</th>
              <th>COUNT</th>
              <th>MAX (MM)</th>
              <th>STATUS</th>
            </tr>
          </thead>
          <tbody>
            {lesions && lesions.length > 0 ? (
              lesions.map((lesion, index) => (
                <tr key={index}>
                  <td className="disease-cell">
                    <span
                      className="color-box"
                      style={{ backgroundColor: lesion.color || LESION_COLORS[lesion.type] || '#999' }}
                    ></span>
                    {lesion.type}
                  </td>
                  <td>{lesion.count ?? '—'}</td>
                  <td>{lesion.count > 0 && Number.isFinite(lesion.max_mm) ? `${approximate ? '≈' : ''}${lesion.max_mm.toFixed(2)}` : '—'}</td>
                  <td>{lesion.status}</td>
                </tr>
              ))
            ) : (
              <tr>
                <td colSpan="4" style={{ textAlign: 'center' }}>No lesions found</td>
              </tr>
            )}
          </tbody>
        </table>
        <p style={{ fontSize: '10px', marginTop: '8px' }}>Status compares presence per lesion type with sample reference labels, not individual counts or sizes.</p>
        {approximate && <p style={{ fontSize: '10px' }}>≈ Size uses the server's fallback scale because the optic disc was not detected.</p>}
      </div>

      {/* ========== 5. FOOTER ========== */}
      <div className="report-footer">
        <p>Research Prototype — For investigational and academic use only. Not certified for clinical diagnosis.</p>
      </div>

    </div>
  );
};

export default ReportTemplate;
